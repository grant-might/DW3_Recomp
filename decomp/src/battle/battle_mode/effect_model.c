/* FIGHTSTG's effect models, the 3D effects of techniques. */

#include "battle/battle_mode.h"

/* An effect model's task: creates its model at its position and rotation on
   layer BATTLE_LAYER_MODELS and ends when its motion is over */
void FIGHTSTG_updateEffectModel(EffectModel *task, Model **children) {
    switch (task->state) {
    case TASK_INIT:
    default:
        task->control.layers[0].enabled = 1;
        task->control.layers[0].layerId = BATTLE_LAYER_MODELS;
        task->control.fighter = 0;
        task->control.layers[0].wireframe = 0;
        task->control.pos.x = task->pos.vx;
        task->control.pos.y = task->pos.vy;
        task->control.pos.z = task->pos.vz;
        task->control.rot.x = task->rot.vx;
        task->control.rot.y = task->rot.vy;
        task->control.rot.z = task->rot.vz;
        children[0] = FIGHTSTG_createPlainModel(task->file, task->motionFile, task->texPos, &task->control);
        task->nextState(task);
        break;
    case TASK_RUN:
        if (task->control.motionDone) {
            task->setState(task, TASK_KILL);
        }
        break;
    case TASK_DONE:
    case TASK_KILL:
        break;
    }
}

