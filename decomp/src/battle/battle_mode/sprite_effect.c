/* Finds 2D effect effect's sheet (FIGHTSTG_spriteEffects,
   FIGHTSTG_effectSheets) and gives its values; returns whether it has one */
s32 FIGHTSTG_findEffectSheet(s32 effect, s32 *images, s32 *sheet, Vec2 *texPos) {
    SpriteEffectEntry *entry;

    for (entry = FIGHTSTG_spriteEffects; entry->id != -1; entry++) {
        if (entry->id == effect) {
            *images = FIGHTSTG_effectSheets[entry->sheet].images;
            *sheet = FIGHTSTG_effectSheets[entry->sheet].sheet;
            *texPos = FIGHTSTG_effectSheets[entry->sheet].texPos;
            return 1;
        }
    }
    return 0;
}

/* A 2D effect's task: starts a sprite animation for each entry of its
   archive (up to 30), on BATTLE_LAYER_FRONT for effects 1000 to 1002 and
   1007, else on BATTLE_LAYER_MODELS, and ends once they all have */
void FIGHTSTG_updateSpriteEffect(SpriteEffect *task, SpriteAnim **children) {
    s32 *archive;
    s32 layerId;
    s32 count;
    s32 i;
    s32 j;
    s32 done;

    switch (task->state) {
    case TASK_INIT:
    default:
        /* getEntry gives the archive's address as a number, getArchiveEntry
           an entry's as a u8 * */
        archive = FILE_CACHE.getEntry(task->file);
        layerId = BATTLE_LAYER_MODELS;
        if (task->effect >= 1000 && task->effect < 1003) {
            layerId = BATTLE_LAYER_FRONT;
        }
        if (task->effect == 1007) {
            layerId = BATTLE_LAYER_FRONT;
        }
        for (count = 0; count < 30; count++) {
            if (archive[count] == 0) {
                break;
            }
        }
        for (i = 0; i < count; i++) {
            children[i] = FIGHTSTG_createSpriteAnim(FILE_CACHE.getArchiveEntry(i, archive), &task->pos,
                                        FIGHTSTG_effectSheets[task->sheet].sheet, &FIGHTSTG_effectSheets[task->sheet].texPos, layerId);
        }
        task->count = count;
        task->nextState(task);
        break;
    case TASK_RUN:
        done = 1;
        for (j = 0; j < task->count; j++) {
            if (children[j] != NULL) {
                done = 0;
                break;
            }
        }
        if (done) {
            task->setState(task, TASK_KILL);
        }
        break;
    case TASK_DONE:
    case TASK_KILL:
        break;
    }
}

/* Starts 2D effect effect (FIGHTSTG_spriteEffects) at pos; killed at once
   when it has no entry */
SpriteEffect *FIGHTSTG_startSpriteEffect(s32 effect, const SVECTOR *pos) {
    SpriteEffect *task = createTask(FIGHTSTG_updateSpriteEffect, sizeof(SpriteEffect), 30 * sizeof(Task *));
    SpriteEffectEntry *entry;

    task->effect = -1;
    for (entry = FIGHTSTG_spriteEffects; entry->id != -1; entry++) {
        if (entry->id == effect) {
            task->effect = effect;
            task->sheet = entry->sheet;
            task->file = entry->file;
            task->pos = *pos;
        }
    }
    if (task->effect == -1) {
        task->setState(task, TASK_KILL);
    }
    return task;
}
