/* The sound test's root task: starts the sound test; START goes back to the
   stage select (MODE_STAGE_SELECT) */
void SOUNDTST_updateScene(Task *task, Task **items) {
    switch (task->state) {
    case TASK_INIT:
    default:
        items[0] = SOUNDTST_createSoundTest();
        task->nextState(task);
        break;
    case TASK_RUN:
        if (PAD.getPressed(0) & (1 << PAD_START)) {
            GAME.funcs.requestMode(MODE_STAGE_SELECT, 0);
            task->nextState(task);
        }
        break;
    case TASK_DONE:
    case TASK_KILL:
        break;
    }
}

/* Creates the sound test's root task */
Task *SOUNDTST_start(void) {
    return createTask(SOUNDTST_updateScene, sizeof(Task), 4);
}

/* Moves a list's cursor by delta within its count, scrolling the eight lines
   shown to keep it in view */
void SOUNDTST_moveCursor(SoundTest *task, s32 delta, s32 *cursor, s32 *top, s32 count) {
    s32 pos = *cursor + delta;

    if (pos >= 0 && pos < count) {
        *cursor = pos;
        if (pos >= *top + 8) {
            *top = pos - 7;
        }
        if (*top > *cursor) {
            *top = *cursor;
        }
    }
}

/* The bank's sound list: cross plays the sound under the cursor for as long
   as it is held, square stops all sounds, triangle goes back to the banks */
void SOUNDTST_playSounds(SoundTest *task, SoundTestWindows *win) {
    SoundTestEntry *list = SOUNDTST_soundLists[task->bankCursor];
    s32 i;
    s32 j;

    switch (task->step) {
    case 0:
    default:
        task->soundCursor = 0;
        task->soundTop = 0;
        task->soundCount = 0;
        while (list[task->soundCount].id != 0) {
            task->soundCount++;
        }
        win->header->setText(win->header, SOUNDTST_banks[task->bankCursor].name);
        task->playing = 0;
        task->nextStep(task);
    case 1:
        break;
    }
    if ((PAD.getPressed(0) | PAD.getRepeated(0)) & (1 << PAD_DOWN)) {
        SOUNDTST_moveCursor(task, 1, &task->soundCursor, &task->soundTop, task->soundCount);
    } else if ((PAD.getPressed(0) | PAD.getRepeated(0)) & (1 << PAD_UP)) {
        SOUNDTST_moveCursor(task, -1, &task->soundCursor, &task->soundTop, task->soundCount);
    } else if (PAD.getPressed(0) & (1 << PAD_SQUARE)) {
        SOUND.stopAll();
    } else if (PAD.getPressed(0) & (1 << PAD_TRIANGLE)) {
        task->setSubstate(task, 0);
    } else if (PAD.getPressed(0) & (1 << PAD_CROSS)) {
        task->voice = SOUND.playSound(list[task->soundCursor].id);
        task->playing = 1;
    } else if (task->playing != 0 && !(PAD.getHeld(0) & (1 << PAD_CROSS))) {
        task->playing = 0;
        SOUND.keyOff(list[task->soundCursor].id, task->voice);
    }
    for (i = 0, j = task->soundTop; i < 8 && list[j].id != 0; i++, j++) {
        win->lines[i]->setText(win->lines[i], list[j].name);
        win->lines[i]->setVisible(win->lines[i], 1);
    }
    for (; i < 8; i++) {
        win->lines[i]->setVisible(win->lines[i], 0);
    }
    win->cursor->setPos(win->cursor, 0x20, (task->soundCursor - task->soundTop) * 16 + 0x46);
}

/* Loads the bank picked, then goes on to its sounds */
void SOUNDTST_loadBank(SoundTest *task, SoundTestWindows *win) {
    switch (task->step) {
    case 0:
    default:
        if (task->bank == 1) {
            SOUND.loadBankInto(0, 1);
        } else {
            SOUND.loadBank(task->bank);
        }
        task->step++;
    case 1:
        break;
    }
    if (SOUND.isLoading() == 0) {
        task->nextSubstate(task);
    }
}

/* The list of the sound banks (VAB) to load: cross picks the one under the
   cursor */
void SOUNDTST_selectBank(SoundTest *task, SoundTestWindows *win) {
    s32 i;
    s32 j;

    switch (task->step) {
    case 0:
    default:
        task->bankCount = 0;
        while (SOUNDTST_banks[task->bankCount].id != 0) {
            task->bankCount++;
        }
        win->header->setText(win->header, "\x81\x7C\x82\xC4\x82\xF1\x82\xBB\x82\xA4\x82\xB7\x82\xE9\x82\x75\x82\x60\x82\x61\x82\xF0\x82\xB9\x82\xF1\x82\xBD\x82\xAD\x82\xB5\x82\xC4\x82\xAD\x82\xBE\x82\xB3\x82\xA2\x81\x7C"); /* "－てんそうするＶＡＢをせんたくしてください－" */
        task->nextStep(task);
    case 1:
        break;
    }
    if ((PAD.getPressed(0) | PAD.getRepeated(0)) & (1 << PAD_DOWN)) {
        SOUNDTST_moveCursor(task, 1, &task->bankCursor, &task->bankTop, task->bankCount);
    } else if ((PAD.getPressed(0) | PAD.getRepeated(0)) & (1 << PAD_UP)) {
        SOUNDTST_moveCursor(task, -1, &task->bankCursor, &task->bankTop, task->bankCount);
    } else if (PAD.getPressed(0) & (1 << PAD_CROSS)) {
        task->bank = SOUNDTST_banks[task->bankCursor].id;
        task->nextSubstate(task);
    }
    for (i = 0, j = task->bankTop; i < 8 && SOUNDTST_banks[j].id != 0; i++, j++) {
        win->lines[i]->setText(win->lines[i], SOUNDTST_banks[j].name);
        win->lines[i]->setVisible(win->lines[i], 1);
    }
    for (; i < 8; i++) {
        win->lines[i]->setVisible(win->lines[i], 0);
    }
    win->cursor->setPos(win->cursor, 0x20, (task->bankCursor - task->bankTop) * 16 + 0x46);
}

/* The sound test's task: sets up the screen and its windows, then picks a
   bank, loads it and plays its sounds; when killed, goes back to the stage
   select */
void SOUNDTST_updateSoundTest(SoundTest *task, SoundTestWindows *win) {
    Layer *res;
    s32 i;

    switch (task->state) {
    case TASK_INIT:
    default:
        GFX.funcs.reset();
        GFX.funcs.allocPrimBuffers(0x5000);
        GFX.funcs.setDisplayMode(SCREEN_WIDTH, SCREEN_HEIGHT, 0, 0);
        res = GFX.funcs.createLayer(&SOUNDTST_screenRect, 1, SCREEN_LAYER);
        res->setBgColor(res, 0x1F, 0x1F, 0x1F);
        win->title = createTextWindow(SCREEN_LAYER, 1, 0x10, 0x1E);
        win->title->setText(win->title, "\x83\x54\x83\x45\x83\x93\x83\x68\x83\x65\x83\x58\x83\x67"); /* "サウンドテスト" */
        win->header = createTextWindow(SCREEN_LAYER, 1, 0x20, 0x32);
        for (i = 0; i < 8; i++) {
            win->lines[i] = createTextWindow(SCREEN_LAYER, 1, 0x30, i * 16 + 0x46);
        }
        win->cursor = createTextWindow(SCREEN_LAYER, 1, 0x20, 0x46);
        win->cursor->setText(win->cursor, SOUNDTST_STR_CURSOR);
        task->nextState(task);
        break;
    case TASK_RUN:
        switch (task->substate) {
        case 0:
        default:
            SOUNDTST_selectBank(task, win);
            break;
        case 1:
            SOUNDTST_loadBank(task, win);
            break;
        case 2:
            SOUNDTST_playSounds(task, win);
            break;
        }
        break;
    case TASK_DONE:
        break;
    case TASK_KILL:
        GAME.funcs.requestMode(MODE_STAGE_SELECT, 0);
        break;
    }
}

/* Creates the sound test */
Task *SOUNDTST_createSoundTest(void) {
    return createTask(SOUNDTST_updateSoundTest, sizeof(SoundTest), sizeof(SoundTestWindows));
}

