/* The stage select's root task: starts the stage select */
void STAGSLCT_updateScene(Task *task, Task **items) {
    switch (task->state) {
    case TASK_INIT:
    default:
        items[0] = STAGSLCT_createStageSelect();
        task->nextState(task);
        break;
    case TASK_RUN:
    case TASK_DONE:
    case TASK_KILL:
        break;
    }
}

/* Creates the stage select's root task */
Task *STAGSLCT_start(void) {
    return createTask(STAGSLCT_updateScene, sizeof(Task), 4);
}

/* Moves the cursor by delta to the next line with a scene, scrolling the
   list at its ends; it stays where it was when there is none */
void STAGSLCT_moveCursor(StageSelect *sel, s32 delta) {
    s32 end = 0;
    s32 top = sel->top;
    s32 cursor = sel->cursor;

    do {
        sel->cursor += delta;
        if (sel->cursor < 0) {
            sel->cursor = 0;
            if (--sel->top < 0) {
                sel->top = 0;
                end = 1;
            }
        }
        if (sel->cursor > sel->lines - 1) {
            sel->cursor = sel->lines - 1;
            if (++sel->top > sel->count - sel->lines) {
                sel->top = sel->count - sel->lines;
                end = 1;
            }
        }
        if (STAGSLCT_entries[sel->top + sel->cursor].scene != 0) {
            return;
        }
    } while (end == 0);
    sel->top = top;
    sel->cursor = cursor;
}

/* Scrolls the list by delta lines, within its ends */
void STAGSLCT_scrollPage(StageSelect *sel, s32 delta) {
    sel->top += delta;
    if (sel->top < 0) {
        sel->top = 0;
        return;
    }
    if (sel->top > sel->count - sel->lines) {
        sel->top = sel->count - sel->lines;
    }
}

/* Shows the console's BIOS version, read from its ROM once and turned into
   full-width characters */
void STAGSLCT_showBiosVersion(StageSelect *sel, StageSelectWindows *win) {
    u8 *src;
    s32 i;
    s32 code;

    if (sel->biosShown == 0) {
        win->bios = createTextWindow(SCREEN_LAYER, 1, 0x10, 0x20);
        /* the BIOS version string in the ROM, in full-width Shift-JIS */
        src = (u8 *)0x1FC0012C;
        for (i = 0; i < 10; i++, src++) {
            /* the match depends on the breaks out of a do/while (0): loop.c
               moves the letter's and the dash's blocks up after the digit's,
               as in the original. And on the code going through an int, as a
               two-byte character constant: negative, it stays an immediate,
               where stored straight to the array it is narrowed to 0x821F
               and loaded into a register before the loop */
            do {
                if (*src >= '0' && *src <= '9') {
                    code = *src - '0' + '\x82\x4F'; /* '０' */
                    STAGSLCT_biosVersion[i] = code;
                    break;
                }
                if (*src >= 'A' && *src <= 'Z') {
                    code = *src - 'A' + '\x82\x60'; /* 'Ａ' */
                    STAGSLCT_biosVersion[i] = code;
                    break;
                }
                if (*src == '-') {
                    code = '\x81\x5C'; /* '―' */
                    STAGSLCT_biosVersion[i] = code;
                    break;
                }
                code = '\x81\x40'; /* '　' */
                STAGSLCT_biosVersion[i] = code;
            } while (0);
            STAGSLCT_biosVersion[i] = (STAGSLCT_biosVersion[i] >> 8) + (STAGSLCT_biosVersion[i] << 8);
        }
        STAGSLCT_biosVersionEnd = 0;
        sel->biosShown = 1;
    }
    win->bios->setPos(win->bios, 0xDC, 0x14);
    win->bios->setText(win->bios, STAGSLCT_biosVersion);
}

/* Select zooms the title in or out; it then scales in 15 frames */
void STAGSLCT_zoomTitle(StageSelect *sel, StageSelectWindows *win) {
    if (sel->fading != 0) {
        sel->fade += sel->fadeStep;
        if (sel->fadeStep > 0) {
            if (sel->fade > 0x1000) {
                sel->fade = 0x1000;
                sel->fading = 0;
            }
        } else if (sel->fade < 0) {
            sel->fade = 0;
            sel->fading = 0;
        }
        win->title->setScale(win->title, sel->fade, sel->fade);
    } else if ((PAD.getPressed(0) >> PAD.getButtonBit(0, PAD_SELECT)) & 1) {
        sel->fading = 1;
        if (sel->fade <= 0) {
            sel->fadeStep = 0x111;
        } else {
            sel->fadeStep = -0x111;
        }
        win->title->setPivot(win->title, 0x37, 0x28);
    }
}

/* Pad 1's R2 and L2 step GAME.progress down and up (0x8000 counts as 0) */
static inline void editProgress(StageSelectWindows *win) {
    if ((PAD.getPressed(0) & (1 << PAD_R2)) || (PAD.getRepeated(0) & (1 << PAD_R2))) {
        if (GAME.progress == 0x8000) {
            GAME.progress = 0;
        }
        if (GAME.progress != 0) {
            GAME.progress--;
        }
    }
    if ((PAD.getPressed(0) & (1 << PAD_L2)) || (PAD.getRepeated(0) & (1 << PAD_L2))) {
        if (GAME.progress == 0x8000) {
            GAME.progress = 0;
        }
        GAME.progress++;
    }
    win->progress->setNumber(win->progress, 0, GAME.progress);
}

/* Pad 2's L1/R1 and L2/R2 change the party's levels and charisma (by 10 when
   repeating); shows party member 0's */
static inline void editParty(StageSelectWindows *win) {
    s32 slot;
    s32 member;
    PartnerStats *stats;
    s32 levelStep;
    s32 charismaStep;
    s32 charisma;
    s32 level;

    charisma = 0;
    level = 0;
    charismaStep = 0;
    levelStep = 0;
    if (!PAD2_HELD(PAD_L1) && PAD2_PRESSED(PAD_R1)) {
        levelStep = 1;
    } else if (!PAD2_HELD(PAD_R1) && PAD2_PRESSED(PAD_L1)) {
        levelStep = -1;
    } else if (!PAD2_HELD(PAD_L1) && PAD2_REPEATED(PAD_R1)) {
        levelStep = 10;
    } else if (!PAD2_HELD(PAD_R1) && PAD2_REPEATED(PAD_L1)) {
        levelStep = -10;
    }
    if (!PAD2_HELD(PAD_L2) && PAD2_PRESSED(PAD_R2)) {
        charismaStep = 1;
    } else if (!PAD2_HELD(PAD_R2) && PAD2_PRESSED(PAD_L2)) {
        charismaStep = -1;
    } else if (!PAD2_HELD(PAD_L2) && PAD2_REPEATED(PAD_R2)) {
        charismaStep = 10;
    } else if (!PAD2_HELD(PAD_R2) && PAD2_REPEATED(PAD_L2)) {
        charismaStep = -10;
    }
    for (slot = 0; slot < 3; slot++) {
        member = GAME.funcs.getPartyMember(slot);
        if (member >= 0) {
            stats = GAME.funcs.getPartnerStats(member);
            stats->stats[STAT_CHARISMA] += charismaStep;
            if (stats->stats[STAT_CHARISMA] >= 1000) {
                stats->stats[STAT_CHARISMA] = 999;
            }
            if (stats->stats[STAT_CHARISMA] < 0) {
                stats->stats[STAT_CHARISMA] = 0;
            }
            stats->stats[STAT_LEVEL] += levelStep;
            if (stats->stats[STAT_LEVEL] >= 100) {
                stats->stats[STAT_LEVEL] = 99;
            }
            if (stats->stats[STAT_LEVEL] <= 0) {
                stats->stats[STAT_LEVEL] = 1;
            }
            if (slot == 0) {
                charisma = stats->stats[STAT_CHARISMA];
                level = stats->stats[STAT_LEVEL];
            }
        }
    }
    win->charisma->setNumber(win->charisma, 0, charisma);
    win->level->setNumber(win->level, 0, level);
}

/* Pad 2's up/down and right/left change BATTLE_SETUP.debugUpDown and
   debugLeftRight, shown while not -1 */
static inline void editBattleDebug(StageSelectWindows *win) {
    if (PAD.getPressed(1) & (1 << PAD_UP)) {
        if (BATTLE_SETUP.debugUpDown != 3) {
            BATTLE_SETUP.debugUpDown++;
        }
    } else if (PAD.getPressed(1) & (1 << PAD_DOWN)) {
        if (BATTLE_SETUP.debugUpDown != -1) {
            BATTLE_SETUP.debugUpDown--;
        }
    } else if (PAD.getPressed(1) & (1 << PAD_RIGHT)) {
        if (BATTLE_SETUP.debugLeftRight != 7) {
            BATTLE_SETUP.debugLeftRight++;
        }
    } else if (PAD.getPressed(1) & (1 << PAD_LEFT)) {
        if (BATTLE_SETUP.debugLeftRight != -1) {
            BATTLE_SETUP.debugLeftRight--;
        }
    }
    if (BATTLE_SETUP.debugUpDown != -1) {
        win->debugUpDown->setNumber(win->debugUpDown, 0, BATTLE_SETUP.debugUpDown + 1);
        win->debugUpDown->setVisible(win->debugUpDown, 1);
    } else {
        win->debugUpDown->setVisible(win->debugUpDown, 0);
    }
    if (BATTLE_SETUP.debugLeftRight != -1) {
        win->debugLeftRight->setNumber(win->debugLeftRight, 0, BATTLE_SETUP.debugLeftRight + 1);
        win->debugLeftRight->setVisible(win->debugLeftRight, 1);
    } else {
        win->debugLeftRight->setVisible(win->debugLeftRight, 0);
    }
}

/*
 * The stage select. Pad 1 moves the cursor (up/down), turns pages (L1/R1),
 * toggles BATTLE_SETUP.randomBattles (Select), starts the entry (Cross: scene 0x300
 * only sets GAME.progress) and, in the European version, cycles the language
 * (Start); L2/R2 change GAME.progress. Pad 2 changes the party's levels
 * (L1/R1) and charisma (L2/R2), and BATTLE_SETUP.debugUpDown (up/down) and
 * debugLeftRight (right/left). TASK_KILL goes to the scene.
 */
void STAGSLCT_updateStageSelect(Task *task, StageSelectWindows *win) {
    /* the task calls (nextState, setState) go through task, the fields
       through this view */
    StageSelect *sel = (StageSelect *)task;
    s32 i;

    switch (sel->state) {
    case TASK_INIT:
    default:
        i = 0;
        GFX.funcs.reset();
        GFX.funcs.allocPrimBuffers(0x5000);
        GFX.funcs.setDisplayMode(SCREEN_WIDTH, SCREEN_HEIGHT, 0, 0);
        {
            Layer *layer = GFX.funcs.createLayer(&STAGSLCT_screenRect, 1, SCREEN_LAYER);
            layer->setBgColor(layer, 0x1F, 0x1F, 0x1F);
        }
        while (STAGSLCT_entries[i].scene != -1) {
            i++;
        }
        if (i < 14) {
            sel->lines = i;
        } else {
            sel->lines = 14;
        }
        sel->count = i;
        sel->top = GAME.stageSelectTop;
        sel->cursor = GAME.stageSelectCursor;
        win->title = createTextWindow(SCREEN_LAYER, 1, 0x10, 0x20);
        win->cursor = createTextWindow(SCREEN_LAYER, 1, 0x10, 0x2C);
        win->cursor->setPos(win->cursor, 0xE, sel->cursor * 12 + 0x2D);
        for (i = 0; i < sel->lines; i++) {
            win->names[i] = createTextWindow(SCREEN_LAYER, 1, 0x18, i * 12 + 0x2D);
            win->titles[i] = createTextWindow(SCREEN_LAYER, 1, 0x98, i * 12 + 0x2D);
            win->names[i]->setText(win->names[i], STAGSLCT_entries[sel->top + i].name);
            win->titles[i]->setText(win->titles[i], STAGSLCT_entries[sel->top + i].title);
        }
        win->region = createTextWindow(SCREEN_LAYER, 1, 0x90, 0x20);
        win->progress = createTextWindow(SCREEN_LAYER, 1, 0xC0, 0x20);
        win->charisma = createTextWindow(SCREEN_LAYER, 1, 0xD0, 0xDC);
        win->level = createTextWindow(SCREEN_LAYER, 1, 0x100, 0xDC);
        win->randomBattles = createTextWindow(SCREEN_LAYER, 1, 0x10, 0xDC);
        win->randomBattles->setNumber(win->randomBattles, 0, BATTLE_SETUP.randomBattles);
        win->debugUpDown = createTextWindow(SCREEN_LAYER, 1, 0x30, 0xDC);
        win->debugLeftRight = createTextWindow(SCREEN_LAYER, 1, 0x50, 0xDC);
        task->nextState(task);
        break;
    case TASK_RUN:
        switch (sel->substate) {
        case 0:
            win->title->setText(win->title, STAGE_SELECT);
            win->cursor->setText(win->cursor, CURSOR);
            sel->nextSubstate(sel);
            break;
        case 1:
            i = sel->top; /* the match depends on i keeping the old top too */
            if (PAD_PRESSED(PAD_UP) || PAD_REPEATED(PAD_UP)) {
                STAGSLCT_moveCursor(sel, -1);
            } else if (PAD_PRESSED(PAD_DOWN) || PAD_REPEATED(PAD_DOWN)) {
                STAGSLCT_moveCursor(sel, 1);
            } else if ((!PAD_HELD(PAD_R1) && PAD_PRESSED(PAD_L1)) ||
                       (!PAD_HELD(PAD_R1) && PAD_REPEATED(PAD_L1))) {
                STAGSLCT_scrollPage(sel, -14);
            } else if ((!PAD_HELD(PAD_L1) && PAD_PRESSED(PAD_R1)) ||
                       (!PAD_HELD(PAD_L1) && PAD_REPEATED(PAD_R1))) {
                STAGSLCT_scrollPage(sel, 14);
            }
            win->cursor->setPos(win->cursor, 0xE, sel->cursor * 12 + 0x2D);
            if (i != sel->top) {
                for (i = 0; i < sel->lines; i++) {
                    win->names[i]->setText(win->names[i], STAGSLCT_entries[sel->top + i].name);
                    win->titles[i]->setText(win->titles[i], STAGSLCT_entries[sel->top + i].title);
                }
            }
            STAGSLCT_showBiosVersion(sel, win);
            if (PAD_PRESSED(PAD_SELECT)) {
                BATTLE_SETUP.randomBattles = BATTLE_SETUP.randomBattles == 0;
                win->randomBattles->setNumber(win->randomBattles, 0, BATTLE_SETUP.randomBattles);
            }
            if (PAD_PRESSED(PAD_CROSS)) {
                if (STAGSLCT_entries[sel->top + sel->cursor].scene != 0) {
                    if (STAGSLCT_entries[sel->top + sel->cursor].scene == 0x300) {
                        GAME.progress = STAGSLCT_entries[sel->top + sel->cursor].arg;
                    } else {
                        task->setState(task, TASK_KILL);
                    }
                }
            }
#if VERSION_EU
            if (PAD.getPressed(0) & (1 << PAD_START)) {
                if (++LANGUAGE == 7) {
                    LANGUAGE = 0;
                }
                MEMCARD_FUNCS.setFileName();
            }
            win->region->setText(win->region, STAGSLCT_regionNames[LANGUAGE]);
#elif VERSION_US
            win->region->setText(win->region, STAGSLCT_regionNames[1]);
#elif VERSION_JP
            win->region->setText(win->region, STAGSLCT_regionNames[0]);
#endif
            editProgress(win);
            editParty(win);
            editBattleDebug(win);
            break;
        }
        break;
    case TASK_KILL:
        if (STAGSLCT_entries[sel->top + sel->cursor].arg & 0x8000) {
            GAME.funcs.requestMode(STAGSLCT_entries[sel->top + sel->cursor].scene, 0);
            GAME.progress = STAGSLCT_entries[sel->top + sel->cursor].arg & 0xFF;
        } else {
            GAME.funcs.requestMode(STAGSLCT_entries[sel->top + sel->cursor].scene,
                                   STAGSLCT_entries[sel->top + sel->cursor].arg);
        }
        GAME.stageSelectTop = sel->top;
        GAME.stageSelectCursor = sel->cursor;
        break;
    case TASK_DONE:
        break;
    }
}

