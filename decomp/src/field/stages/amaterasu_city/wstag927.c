/* After event 1608, with Kurt: starts the stage's event battle 0 and keeps it from playing again */
void endEvent1608(void) {
    FLAGS_00.applyAction(FLAG(0x10, 0xC), 1);
    FLAGS_00.applyAction(EVENT_BATTLE(0), 1);
}

